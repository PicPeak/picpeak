/** An error the routes answer with 409 and its code. */
function trashError(code, message) {
  return Object.assign(new Error(message), { code, statusCode: 409 });
}

const nowIso = () => new Date().toISOString();

const isStale = (row) => Date.now() - Date.parse(row.state_changed_at) >= STALE_MS;

/**
 * Renew a claim, right before a step that cannot be taken back. Throws when
 * the row is no longer this caller's: the sweep took it over, or it is gone.
 * `extra` columns are written with the new token.
 */
async function holdClaim(row, extra = {}) {
  const stamp = nowIso();
  const held = await db('photo_trash')
    .where({ id: row.id, state: row.state, state_changed_at: row.state_changed_at })
    .update({ ...extra, state_changed_at: stamp });
  if (held !== 1) throw trashError('TRASH_BUSY', `Trash row ${row.id} was taken over by another process`);
  Object.assign(row, extra, { state_changed_at: stamp });
}

/** Is this S3 object the one the operation noted on the row (move_tag)? */
const isTagged = (row, stat) => Boolean(row.move_tag && stat && stat.etag === row.move_tag);

async function sha256Of(storage, key) {
  const hash = crypto.createHash('sha256');
  for await (const chunk of await storage.get(key)) hash.update(chunk);
  return hash.digest('hex');
}

/**
 * After an interrupted move there is a file at the photo's place and one
 * under trash_key (S3 copies and then deletes; local storage links and then
 * unlinks, see moveIntoPlace). Is the one at the photo's place this
 * operation's, so that one of the two is surplus? Yes when it carries the
 * noted ETag (S3). Otherwise the bytes decide: of two identical files either
 * may go, and nothing else may. Read as streams, and only on this path,
 * which a crash leads to.
 */
async function isSameObject(storage, row, placeKey, atPlace, inTrash) {
  if (isTagged(row, atPlace)) return true;
  if (Number(atPlace.size) !== Number(inTrash.size)) return false;
  return (await sha256Of(storage, placeKey)) === (await sha256Of(storage, row.trash_key));
}

/**
 * The gallery's row, before anything else in a transaction that goes on to
 * lock a trash row and photo, feedback or guest rows: deleting a gallery
 * takes the event first and those after (deleteEventCascade), and a
 * transaction that took them the other way round would deadlock with it on
 * PostgreSQL. SQLite has one writer.
 */
async function lockEvent(trx, eventId) {
  if (trx.client.config.client === 'pg') await trx('events').where({ id: eventId }).forUpdate().first('id');
}

/**
 * First statement of a transaction that closes a claim. The write takes the
 * row (a row lock on PostgreSQL, the write lock on SQLite) before anything
 * is read, and fails when the claim is no longer this caller's.
 */
async function lockClaim(trx, row) {
  const locked = await trx('photo_trash')
    .where({ id: row.id, state: row.state, state_changed_at: row.state_changed_at })
    .update({ state: row.state });
  if (locked !== 1) throw trashError('TRASH_BUSY', `Trash row ${row.id} changed underneath`);
}

/**
 * Local storage: move a file to a photo's place only if nothing is there.
 * The check a restore makes first leaves a gap, and a rename would overwrite
 * a file that was dropped into the watched folder in it. A hard link is
 * refused by the filesystem when the name is taken; where links are not
 * possible (some network mounts, another device) an exclusive copy is.
 * Between the link and the unlink the file has both names: isSameObject.
 */
async function moveIntoPlace(storage, fromKey, toKey) {
  const from = storage.resolveLocalPath(fromKey);
  const to = storage.resolveLocalPath(toKey);
  const taken = () => trashError('RESTORE_TARGET_EXISTS', `A file has appeared at ${toKey}; it was not overwritten`);
  await fs.mkdir(path.dirname(to), { recursive: true });
  try {
    await fs.link(from, to);
  } catch (error) {
    if (error.code === 'EEXIST') throw taken();
    if (!['EPERM', 'ENOTSUP', 'EOPNOTSUPP', 'ENOSYS', 'EXDEV', 'EMLINK'].includes(error.code)) throw error;
    try {
      await fs.copyFile(from, to, fsConstants.COPYFILE_EXCL);
    } catch (copyError) {
      if (copyError.code === 'EEXIST') throw taken();
      // Exclusive: whatever is there after a failed copy is this copy's.
      await fs.unlink(to).catch(() => {});
      throw copyError;
    }
  }
  await fs.unlink(from);
}

/**
 * Move a file for the claim `row`. Local storage renames, which is atomic.
 * S3 copies and then deletes: the claim is renewed in between, so a caller
 * that lost it while the copy ran leaves the source alone, and its callers
 * deal with the copy that arrived late (trashPhoto, restorePhoto).
 *
 * `intoPlace`: the destination is the photo's place, where other files can
 * turn up, not a trash_key. Local storage then moves without overwriting
 * (moveIntoPlace). On S3 the ETag of the copy is noted on the row with the
 * renewal (move_tag): whoever settles the row later knows the object there
 * as this operation's own by it. The S3 adapter has no conditional copy, so
 * there an object arriving between the caller's check and the copy is
 * overwritten.
 */
async function moveClaimed(row, fromKey, toKey, { intoPlace = false } = {}) {
  const tagDestination = intoPlace;
  const storage = getStorage();
  await holdClaim(row);
  if (storage.kind() !== 's3') {
    if (intoPlace) await moveIntoPlace(storage, fromKey, toKey);
    else await storage.rename(fromKey, toKey);
    return;
  }
  await storage.copy(fromKey, toKey);
  const landed = tagDestination ? await storage.stat(toKey).catch(() => null) : null;
  const tag = (landed && landed.etag) || null;
  // Without the note the source stays: once it is gone nothing could tell
  // the copy from another object any more. The caller undoes the move.
  if (tagDestination && !tag) throw new Error(`Could not identify the copy at ${toKey}; the move was not completed`);
  try {
    await holdClaim(row, tagDestination ? { move_tag: tag } : {});
  } catch (error) {
    throw Object.assign(error, { lateCopyTag: tag });
  }
  await storage.delete(fromKey);
}

/** Days a deleted photo stays restorable; 0 deletes at once, as before the trash. */
async function getRetentionDays() {
  try {
    const row = await db('app_settings').where({ setting_key: SETTING_KEY }).first();
    let value = row ? row.setting_value : null;
    if (typeof value === 'string') {
      try { value = JSON.parse(value); } catch { /* keep the string */ }
    }
    const days = Number(value);
    if (value === null || value === '' || !Number.isInteger(days) || days < 0) return DEFAULT_RETENTION_DAYS;
    return Math.min(days, MAX_RETENTION_DAYS);
  } catch (error) {
    // Unknown is not "0": keep what was deleted.
    logger.error('Failed to read the photo trash retention setting:', error.message);
    return DEFAULT_RETENTION_DAYS;
  }
}

async function dropDerivedFiles(photo) {
  const storage = getStorage();
  for (const key of [photo.thumbnail_path, photo.hero_path, photo.preview_path, photo.web_path, photo.watermark_path]) {
    if (key) await storage.delete(key).catch(() => {});
  }
  const imageProcessor = require('./imageProcessor');
  await imageProcessor.deletePreviewTiers(photo).catch(() => {});
  await imageProcessor.deleteThumbnailTiers(photo).catch(() => {});
}

/**
 * The child rows of a photo, inside the trashing transaction: the ones a user
 * would miss are returned for the trash row, every one is deleted (SQLite does
 * not enforce the foreign keys, so nothing cascades there).
 */
async function detachChildren(trx, photo, event) {
  const photoId = photo.id;
  const children = {
    event_slug: event.slug,
    feedback: await trx('photo_feedback').where({ photo_id: photoId }).forUpdate(),
    admin_marks: await trx('photo_admin_marks').where({ photo_id: photoId }),
    transfer_files: await trx('transfer_files').where({ photo_id: photoId }),
    event_hero: Number(event.hero_photo_id) === Number(photoId),
    category_hero_ids: await trx('photo_categories').where({ hero_photo_id: photoId }).pluck('id'),
  };

  // Faces and embeddings are biometric and regenerable: never kept. The
  // purge also rebuilds the people the faces belonged to.
  let purgePhotoFaces = null;
  try { ({ purgePhotoFaces } = require('./faceProcessor')); } catch { /* face detection not installed */ }
  if (purgePhotoFaces) await purgePhotoFaces(photoId, trx);
  else await trx('photo_faces').where({ photo_id: photoId }).del();

  await trx('photo_feedback').where({ photo_id: photoId }).del();
  await trx('photo_admin_marks').where({ photo_id: photoId }).del();
  await trx('transfer_files').where({ photo_id: photoId }).del();
  // Download grants and per-view logs end with the photo's time in the gallery.
  await trx('event_download_grants').where({ photo_id: photoId }).del();
  await trx('image_access_logs').where({ photo_id: photoId }).del();
  await trx('events').where({ hero_photo_id: photoId }).update({ hero_photo_id: null });
  await trx('photo_categories').where({ hero_photo_id: photoId }).update({ hero_photo_id: null });
  return children;
}

/**
 * Step 3 of a trashing: the photo row and its children go, the trash row
 * comes to rest, in one transaction.
 *
 * The photo row may already be gone: on local storage the folder watcher
 * drops the row of a file it sees leave events/active, and step 2 is such a
 * move. The file is in the trash by then, so that is not a reason to stop:
 * the row read before the move stands in for the live one.
 */
async function commitTrash(row, photo, event) {
  await db.transaction(async (trx) => {
    await lockEvent(trx, row.event_id);
    await lockClaim(trx, row);
    // FOR UPDATE on PostgreSQL, here and for the feedback: a guest merge that
    // is rewriting these rows finishes first, and the snapshot holds what it
    // wrote (mergeGuests).
    const live = (await trx('photos').where({ id: row.photo_id, event_id: row.event_id }).forUpdate().first()) || photo;
    const children = await detachChildren(trx, live, event);
    await trx('photos').where({ id: row.photo_id, event_id: row.event_id }).del();
    await trx('photo_trash').where({ id: row.id }).update({
      state: 'trashed',
      state_changed_at: nowIso(),
      move_tag: null,
      photo_row: JSON.stringify(live),
      children: JSON.stringify(children),
    });
  });
}

/**
 * A trashing that did not reach step 3: put things back, without ever
 * deleting the only copy of the file. For a caller that holds the claim.
 *   - a file at both keys, and the one in place is the photo's original
 *     (isSameObject): a move stopped halfway, the copy under trash_key is
 *     surplus; drop it and the pending row
 *   - a file at both keys otherwise: the file in place is not this photo's
 *     original but one somebody put there since. The original cannot go
 *     back over it and must not be deleted: finish the trashing. The other
 *     file stays for the importer.
 *   - file in the trash, photo row still there: move it back
 *   - file in the trash, photo row gone (the watcher, see commitTrash):
 *     there is no gallery row to give it back to, so finish the trashing
 * Returns true when the photo ended up in the trash after all.
 */
async function undoPending(row) {
  if (row.trash_key) {
    const storage = getStorage();
    const inPlace = await storage.stat(row.original_key);
    const inTrash = await storage.stat(row.trash_key);
    const surplusCopy = inPlace && inTrash && await isSameObject(storage, row, row.original_key, inPlace, inTrash);
    if (surplusCopy) {
      await holdClaim(row);
      await storage.delete(row.trash_key);
    } else if (inTrash) {
      if (inPlace || !(await db('photos').where({ id: row.photo_id, event_id: row.event_id }).first('id'))) {
        const event = await db('events').where({ id: row.event_id }).first();
        await commitTrash(row, JSON.parse(row.photo_row), event || { id: row.event_id });
        return true;
      }
      // Tagged: should this stop between copy and delete, the next attempt
      // knows the object in place as the original again.
      await moveClaimed(row, row.trash_key, row.original_key, { intoPlace: true });
    }
  }
  await db('photo_trash').where({ id: row.id, state: 'pending', state_changed_at: row.state_changed_at }).del();
  return false;
}

/**
 * Step 1 of a trashing: the pending row. The partial unique index of
 * migration 294 lets one in per photo, so of two requests one gets here and
 * the other is told the photo is busy. A row an earlier attempt left behind
 * (older than STALE_MS) is put right first; `trashed: true` when that ended
 * with the photo in the trash.
 */
async function claimPending(base) {
  for (let attempt = 0; ; attempt += 1) {
    try {
      const inserted = await db('photo_trash').insert(base).returning('id');
      return { row: { ...base, id: inserted[0]?.id ?? inserted[0] } };
    } catch (error) {
      if (!isUniqueViolation(error)) throw error;
    }
    const leftover = await db('photo_trash').where({ photo_id: base.photo_id, state: 'pending' }).first();
    if (attempt > 0 || !leftover || !isStale(leftover)) {
      throw trashError('TRASH_BUSY', `Photo ${base.photo_id} is already being moved to the trash`);
    }
    await holdClaim(leftover);
    if (await undoPending(leftover)) return { trashed: true };
  }
}

/**
 * For a trashing that lost its claim. Whoever took the row over has settled
 * the file, with one exception: nobody did when the row is simply gone (its
 * gallery was deleted meanwhile) or was settled before an S3 copy arrived.
 * What then lies under this trashing's own key, which no row names and none
 * ever will again, is nobody's, and nothing would ever purge it.
 */
async function dropAbandonedTrashFile(row) {
  if (!row.trash_key) return;
  if (await db('photo_trash').where({ trash_key: row.trash_key }).first('id')) return;
  await getStorage().delete(row.trash_key);
}

/**
 * Move one photo to the trash. Returns false, having changed nothing, when a
 * managed photo's original is already missing: there is nothing to keep, and
 * the caller deletes the row the way it always did. Throws when the photo
 * could not be trashed; it is then still in the gallery, untouched.
 */
async function trashPhoto(event, photo, admin, retentionDays) {
  const storage = getStorage();
  let originalKey;
  try {
    originalKey = resolvePhotoStorageKey(event, photo);
  } catch {
    // A row without a path names no file.
    return false;
  }

  const now = new Date();
  const base = {
    photo_id: photo.id,
    event_id: event.id,
    state: 'pending',
    state_changed_at: now.toISOString(),
    filename: photo.original_filename || photo.filename,
    size_bytes: Number(photo.size_bytes) || 0,
    original_key: originalKey,
    trash_key: originalKey
      ? path.posix.join(TRASH_PREFIX, String(event.id), crypto.randomUUID(), path.posix.basename(originalKey))
      : null,
    deleted_at: now.toISOString(),
    deleted_by: admin?.id ?? null,
    deleted_by_name: admin?.username ?? null,
    purge_after: new Date(now.getTime() + retentionDays * 86400000).toISOString(),
    photo_row: JSON.stringify(photo),
    children: '{}',
  };

  // The claim comes before any look at the file: an original that is missing
  // may be in the trash for a request that has not committed yet, and only
  // the holder of the pending row can tell.
  const claim = await claimPending(base);
  if (claim.trashed) return true;
  const { row } = claim;
  const release = () => db('photo_trash')
    .where({ id: row.id, state: 'pending', state_changed_at: row.state_changed_at }).del();

  let live;
  let stat = null;
  try {
    // The caller read `photo` before the claim; another request may have
    // trashed it since.
    live = await db('photos').where({ id: photo.id, event_id: event.id }).first();
    if (!live) throw trashError('PHOTO_GONE', `Photo ${photo.id} is no longer in the gallery`);
    if (resolvePhotoStorageKey(event, live) !== originalKey) {
      throw trashError('TRASH_BUSY', `Photo ${photo.id} changed while it was being deleted`);
    }
    stat = originalKey ? await storage.stat(originalKey) : null;
    // S3 moves an object with CopyObject, which stops at 5 GB, and the adapter
    // has no multipart copy. Refused before anything is touched.
    if (stat && storage.kind() === 's3' && Number(stat.size) > S3_COPY_LIMIT_BYTES) {
      throw trashError('TRASH_TOO_LARGE',
        `"${photo.original_filename || photo.filename}" is larger than 5 GB, which S3 cannot move to the trash. `
        + 'It was not deleted. Set the trash retention to 0 to delete it for good.');
    }
  } catch (error) {
    await release().catch(() => {});
    throw error;
  }
  if (originalKey && !stat) {
    await release();
    return false;
  }

  try {
    if (row.trash_key) {
      // Which object is being moved, noted before it is copied (undoPending).
      await holdClaim(row, { move_tag: stat.etag || null });
      await moveClaimed(row, row.original_key, row.trash_key);
    }
    // Before the transaction, like the delete it replaces: the watcher must
    // not re-import the file while the row is in the trash.
    await require('./externalImportService').recordExclusions(Number(event.id), [live]);

    await commitTrash(row, live, event);
  } catch (error) {
    let trashedAfterAll = false;
    let held = true;
    try {
      await holdClaim(row);
    } catch {
      held = false;
    }
    try {
      if (held) trashedAfterAll = await undoPending(row);
      // Not this caller's any more: the sweep took the row over and settles
      // it, or the row went with its gallery.
      else await dropAbandonedTrashFile(row);
    } catch (undoError) {
      // The sweep finishes the undo; the pending row still names both keys.
      logger.error(`Could not undo the trashing of photo ${photo.id}`, { error: undoError.message });
    }
    if (!trashedAfterAll) throw error;
  }

  await dropDerivedFiles(live).catch((error) => {
    logger.warn(`Could not drop derived files of trashed photo ${photo.id}`, { error: error.message });
  });
  return true;
}

function publicRow(row) {
  let mediaType = 'image';
  try { mediaType = JSON.parse(row.photo_row).media_type || 'image'; } catch { /* keep the default */ }
  return {
    id: row.id,
    photo_id: row.photo_id,
    filename: row.filename,
    media_type: mediaType,
    size_bytes: Number(row.size_bytes) || 0,
    deleted_at: row.deleted_at,
    deleted_by_name: row.deleted_by_name,
    purge_after: row.purge_after,
  };
}

async function listTrash(eventId) {
  const rows = await db('photo_trash')
    .where({ event_id: eventId, state: 'trashed' })
    .orderBy('deleted_at', 'desc')
    .orderBy('id', 'desc');
  return rows.map(publicRow);
}

/**
 * A photo row without a guest who uploaded it: what photoCredit's
 * clearGuestCredits does to the live rows of a forgotten guest.
 */
function withoutGuest(photoRow, guestId) {
  if (Number(photoRow.uploader_guest_id) !== Number(guestId)) return photoRow;
  if (photoRow.credit_source === 'guest') {
    return { ...photoRow, credit_name: null, credit_source: null, uploader_guest_id: null, credit_visible_to_guests: false };
  }
  if (photoRow.credit_source === 'manual') return { ...photoRow, credit_name: null, uploader_guest_id: null };
  return { ...photoRow, uploader_guest_id: null };
}

/**
 * A guest was forgotten (the admin removed them, or they asked): the same
 * happens to what the trash holds of them as to their live rows. Their
 * feedback keeps its count and loses the identity
 * (feedbackService.anonymizeGuestFeedback), their name leaves the photos
 * they uploaded. Not left for the purge: a snapshot is restorable data.
 *
 * Called by photoCredit.clearGuestCredits, the last step of both erasure
 * routes, so after the live rows were cleared. Each snapshot is rewritten
 * under its row's lock: a trashing that is committing has either read live
 * rows that were already cleared, or its snapshot is scrubbed here once it
 * is in; a restore has either read the scrubbed snapshot, or it committed
 * first, and what it put back is cleared after the loop (the feedback here,
 * the credits by the caller).
 */
async function forgetGuest(guestId) {
  const id = Number(guestId);
  const guest = await db('gallery_guests').where({ id }).first('event_id');
  if (!guest) return 0;
  let changed = 0;
  for (const rowId of await db('photo_trash').where({ event_id: guest.event_id }).pluck('id')) {
    changed += await db.transaction(async (trx) => {
      const row = await trx('photo_trash').where({ id: rowId }).forUpdate().first('id', 'photo_row', 'children');
      if (!row) return 0;
      const photoRow = JSON.parse(row.photo_row);
      const children = JSON.parse(row.children || '{}');
      const scrubbedRow = withoutGuest(photoRow, id);
      let touched = scrubbedRow !== photoRow;
      const feedback = (children.feedback || []).map((entry) => {
        if (Number(entry.guest_id) !== id) return entry;
        touched = true;
        return { ...entry, guest_id: null, guest_name: null, guest_email: null };
      });
      if (!touched) return 0;
      await trx('photo_trash').where({ id: rowId })
        .update({ photo_row: JSON.stringify(scrubbedRow), children: JSON.stringify({ ...children, feedback }) });
      return 1;
    });
  }
  await db('photo_feedback').where({ guest_id: id })
    .update({ guest_id: null, guest_name: null, guest_email: null });
  return changed;
}

/**
 * Guests were merged into `survivor` (adminGuests): what the trash holds of
 * the merged ones follows, as their live rows do. Their uploads and feedback
 * in the snapshots move to the survivor, and of two choices of one kind on a
 * photo the later one stays (feedbackService.mergeGuestFeedback). Without
 * this a restore would find the merged guest marked deleted and bring the
 * rows back without a name.
 *
 * Runs in the merge's transaction and before it locks the guest rows: every
 * writer takes the event, then a trash row, and guest or feedback rows after, so a
 * restore that is inserting rows for these guests and the merge cannot wait
 * on each other. A trashing or restore that holds a row finishes before the
 * merge reads it; one that comes later waits for the merge to commit.
 */
async function mergeGuests(trx, survivor, sourceGuestIds) {
  const sources = new Set(sourceGuestIds.map(Number));
  const keepId = Number(survivor.id);
  const name = require('./photoCredit').creditName(survivor.name);
  const { lastMutatedFirst } = require('./feedbackService');
  let changed = 0;
  await lockEvent(trx, survivor.event_id);
  for (const rowId of await trx('photo_trash').where({ event_id: survivor.event_id }).pluck('id')) {
    const row = await trx('photo_trash').where({ id: rowId }).forUpdate().first('photo_row', 'children');
    if (!row) continue;
    let photoRow = JSON.parse(row.photo_row);
    const children = JSON.parse(row.children || '{}');
    let touched = false;
    if (sources.has(Number(photoRow.uploader_guest_id))) {
      // photoCredit.reassignGuestCredits
      photoRow = {
        ...photoRow,
        uploader_guest_id: keepId,
        ...(name && photoRow.credit_source === 'guest' ? { credit_name: name } : {}),
      };
      touched = true;
    }
    let feedback = (children.feedback || []).map((entry) => {
      if (!sources.has(Number(entry.guest_id))) return entry;
      touched = true;
      return { ...entry, guest_id: keepId, guest_identifier: survivor.identifier };
    });
    if (!touched) continue;

    const seen = new Set();
    const duplicates = new Set();
    for (const entry of feedback.filter((e) => Number(e.guest_id) === keepId).sort(lastMutatedFirst)) {
      if (entry.feedback_type === 'comment' || entry.is_hidden === true || Number(entry.is_hidden) === 1) continue;
      if (seen.has(entry.feedback_type)) duplicates.add(entry);
      else seen.add(entry.feedback_type);
    }
    feedback = feedback.filter((entry) => !duplicates.has(entry));
    // The counters in photo_row are from before the merge; the restore
    // counts again (insertRestored).
    await trx('photo_trash').where({ id: rowId })
      .update({ photo_row: JSON.stringify(photoRow), children: JSON.stringify({ ...children, feedback }) });
    changed += 1;
  }
  return changed;
}

/**
 * For the folder watcher: is the file that just left `storageKey` this
 * photo's original on its way into the trash? Then the removal is the app's
 * own move, not someone deleting the file, and the photo row and its children
 * belong to the trashing transaction.
 *
 * Only a pending row: once the trashing has committed the photo row is gone,
 * and a row the watcher still finds under that id and path is another photo
 * (an id handed out again after a database restore), whose file really left.
 */
async function ownsOutgoingFile(photoId, storageKey) {
  return Boolean(await db('photo_trash')
    .where({ photo_id: photoId, original_key: storageKey, state: 'pending' }).first('id'));
}

/**
 * For the folder watcher and the S3 importer: is a restore putting a file at
 * `storageKey` right now? Its photo row follows in the restore's transaction,
 * so the file must not be imported as a new photo.
 */
async function claimsIncomingFile(storageKey) {
  return Boolean(await db('photo_trash').where({ original_key: storageKey, state: 'restoring' }).first('id'));
}

/** Where a trashed managed photo goes back to, with the event's current slug. */
function restoredPath(event, photoRow, children) {
  const oldSlug = children.event_slug;
  if (!oldSlug || oldSlug === event.slug || !photoRow.path) return photoRow.path;
  // The same rewrite an event rename applies to its photos.
  return photoRow.path.replace(oldSlug, event.slug);
}

const SNAPSHOT_TABLES = ['photos', 'photo_feedback', 'photo_admin_marks', 'transfer_files'];

/**
 * A snapshot is JSON of rows as the engine returned them. One taken on SQLite
 * holds epoch numbers where PostgreSQL wants a timestamp and 0/1 where it
 * wants a boolean, and the supported move from SQLite to PostgreSQL carries
 * the trash along with those values inside: PostgreSQL would reject the
 * insert and the photo could never be restored. Returns (table, row) => row
 * for the engine in use, coercing per column type the way the importer does
 * for the tables themselves (picpeakImportService.coerceForTargetEngine).
 * The identity on SQLite, where a row goes back as it was. Read before the
 * restore's transaction: a schema lookup inside one deadlocks SQLite.
 */
async function snapshotCoercion() {
  if (db.client.config.client !== 'pg') return (table, row) => row;
  const { coerceForTargetEngine } = require('./picpeakImportService');
  const types = {};
  for (const table of SNAPSHOT_TABLES) {
    const timestamps = [];
    const booleans = [];
    for (const [name, meta] of Object.entries(await db(table).columnInfo())) {
      const type = String(meta.type || '').toLowerCase();
      if (type.includes('timestamp') || type === 'date' || type === 'datetime') timestamps.push(name);
      else if (type === 'boolean' || type === 'bool') booleans.push(name);
    }
    types[table] = { timestamps, booleans };
  }
  return (table, row) => coerceForTargetEngine([row], types[table])[0];
}

/**
 * Step 3 of a restore. The photo gets its old id back when that is still
 * free. It is not always: restoring a database backup resets the id sequence
 * to the highest live photo, so a later upload can hold the id of a photo
 * still in the trash. The photo then comes back under a new id; its child
 * rows are written from the snapshot either way and follow it.
 * Returns the id the photo now has.
 */
async function insertRestored(trx, event, row, columns, forEngine) {
  await lockEvent(trx, event.id);
  await lockClaim(trx, row);
  // The snapshot as it is now, under the lock: a guest forgotten since the
  // caller read the row is already out of it (forgetGuest).
  const snapshot = await trx('photo_trash').where({ id: row.id }).first('photo_row', 'children');
  const photoRow = JSON.parse(snapshot.photo_row);
  const children = JSON.parse(snapshot.children || '{}');
  photoRow.path = restoredPath(event, photoRow, children);

  const record = {};
  for (const [key, value] of Object.entries({ ...photoRow, ...DERIVED_RESET })) {
    if (columns.has(key)) record[key] = value;
  }
  delete record.id;
  record.event_id = event.id;
  // Processing reads this: a restored photo was announced when it was
  // uploaded and is not announced again (photoProcessor.processPhoto). A
  // photo held for review has not been announced yet: approving it clears
  // the mark (uploadReviewService.moderatePhotos). Set on every restore all
  // the same, because it is also what tells this row from the one the
  // folder watcher may have read before the photo was trashed
  // (fileWatcher.removePhoto).
  if (columns.has('restored_from_trash_at')) record.restored_from_trash_at = nowIso();
  const keepsId = !(await trx('photos').where({ id: row.photo_id }).first('id'));
  if (keepsId) record.id = row.photo_id;

  // What the row pointed at may have been deleted while it was in the trash.
  const exists = async (table, id, extra = {}) => Boolean(id && await trx(table).where({ id, ...extra }).first('id'));
  // A category is the gallery's own or a global one (event_id NULL).
  const categoryStands = record.category_id && await trx('photo_categories').where({ id: record.category_id })
    .where((q) => q.where('event_id', event.id).orWhereNull('event_id')).first('id');
  if (!categoryStands) record.category_id = null;
  if (!(await exists('photo_categories', record.folder_id, { event_id: event.id }))) record.folder_id = null;
  if (!(await exists('admin_users', record.uploaded_by_admin_id))) record.uploaded_by_admin_id = null;
  // A guest who was removed is a row marked deleted, not a missing one.
  const guestStands = async (guestId) => {
    const guest = guestId && await trx('gallery_guests').where({ id: guestId }).first('is_deleted');
    return Boolean(guest) && guest.is_deleted !== true && Number(guest.is_deleted) !== 1;
  };
  if (record.uploader_guest_id && !(await guestStands(record.uploader_guest_id))) {
    Object.assign(record, withoutGuest(record, record.uploader_guest_id));
  }

  const inserted = await insertPhotoWithinCap(forEngine('photos', record), photoCapOf(event), trx);
  if (!inserted) throw trashError('PHOTO_CAP_REACHED', photoCapError(photoCapOf(event)).error);
  const photoId = keepsId ? row.photo_id : (inserted[0]?.id ?? inserted[0]);
  if (keepsId && trx.client.config.client === 'pg') {
    // An explicit id does not move a PostgreSQL sequence, and after a backup
    // restore the id can lie ahead of it: a later upload would collide.
    await trx.raw(
      'SELECT setval(seq, GREATEST(nextval(seq), (SELECT MAX(id) FROM photos))) FROM (SELECT pg_get_serial_sequence(?, ?) AS seq) s',
      ['photos', 'id']
    );
  }

  for (const feedback of children.feedback || []) {
    const { id: _id, ...rest } = feedback;
    // A guest that no longer exists keeps the count, not the name: what
    // forgetting a guest does to feedback in the gallery.
    const kept = rest.guest_id && !(await guestStands(rest.guest_id))
      ? { ...rest, guest_id: null, guest_name: null, guest_email: null }
      : rest;
    await trx('photo_feedback').insert(forEngine('photo_feedback', { ...kept, photo_id: photoId, event_id: event.id }));
  }
  for (const mark of children.admin_marks || []) {
    const { id: _id, ...rest } = mark;
    if (await exists('admin_users', rest.admin_id)) {
      await trx('photo_admin_marks').insert(forEngine('photo_admin_marks', { ...rest, photo_id: photoId, event_id: event.id }));
    }
  }
  for (const file of children.transfer_files || []) {
    const { id: _id, ...rest } = file;
    if (await exists('transfers', rest.transfer_id)) {
      await trx('transfer_files').insert(forEngine('transfer_files', { ...rest, photo_id: photoId }));
    }
  }
  if ((children.feedback || []).length) {
    // The counters in the snapshot are from when the photo was trashed. What
    // they count can have changed since: guests merged or forgotten, the
    // gallery's feedback mode switched. Counted from the rows that came back.
    await require('./feedbackService').updatePhotoFeedbackStats(photoId, trx);
  }
  if (children.event_hero) {
    await trx('events').where({ id: event.id }).whereNull('hero_photo_id').update({ hero_photo_id: photoId });
  }
  if ((children.category_hero_ids || []).length) {
    // The gallery's own categories and global ones (event_id NULL), which
    // can carry a cover too.
    await trx('photo_categories').whereIn('id', children.category_hero_ids)
      .where((q) => q.where('event_id', event.id).orWhereNull('event_id'))
      .whereNull('hero_photo_id').update({ hero_photo_id: photoId });
  }
  if (record.external_relpath) {
    await trx('external_import_exclusions')
      .where({ event_id: event.id, external_relpath: record.external_relpath }).del();
  }

  await trx('photo_trash').where({ id: row.id }).del();
  return photoId;
}

/**
 * A restore that did not reach its transaction: bring the file to rest in
 * the trash and the row back to `trashed`. For a caller that holds the claim.
 *
 * `moved` says whether the restore got as far as moving the file. If not,
 * nothing at the destination is its own: a file there was put by somebody
 * else (a drop into the watched folder that awaits import) and stays.
 * Otherwise:
 *   - file in the trash and at the destination: the move stopped halfway
 *     if the one at the destination is what the restore put there
 *     (isSameObject); it goes. Any other file there is not this photo's.
 *   - file at the destination only: move it back; on S3, if it is the
 *     object the restore noted
 * A file a photo row names is that photo's, whatever else.
 */
async function settleRestore(row, moved) {
  if (row.trash_key && moved) {
    const storage = getStorage();
    const targetKey = row.original_key;
    const inTrash = await storage.stat(row.trash_key);
    const atTarget = await storage.stat(targetKey);
    const relative = targetKey.replace(/^events\/active\//, '');
    const mine = atTarget
      && !(await db('photos').where({ event_id: row.event_id }).whereIn('path', [relative, targetKey]).first('id'));
    const s3 = storage.kind() === 's3';
    if (mine && inTrash) {
      if (await isSameObject(storage, row, targetKey, atTarget, inTrash)) {
        await holdClaim(row);
        await storage.delete(targetKey);
      }
    } else if (mine && (!s3 || isTagged(row, atTarget))) {
      await moveClaimed(row, targetKey, row.trash_key);
    }
  }
  const settled = await db('photo_trash')
    .where({ id: row.id, state: 'restoring', state_changed_at: row.state_changed_at })
    .update({ state: 'trashed', state_changed_at: nowIso(), restore_move_at: null, move_tag: null });
  if (settled !== 1) throw trashError('TRASH_BUSY', `Trash row ${row.id} was taken over by another process`);
}

/**
 * The claim of a restore that failed, to undo it under. Normally the restore
 * still holds it. When the sweep took the row over (an S3 copy can run past
 * STALE_MS) it has put the row back to `trashed` without seeing a copy that
 * had not arrived yet. That copy (`lateCopyTag`, from moveClaimed) now lies
 * at the photo's place with no row and no claim, where the importer would
 * publish it as a new photo: claim the row again, as a restore that has
 * moved that object, and settleRestore removes it. Throws when the row is neither: somebody else is at work on it, and
 * no file is touched.
 */
async function retakeRestore(claim, moved, lateCopyTag) {
  try {
    await holdClaim(claim);
    return;
  } catch (error) {
    if (!moved || !lateCopyTag) throw error;
  }
  const retaken = {
    state: 'restoring', state_changed_at: nowIso(), original_key: claim.original_key,
    restore_move_at: nowIso(), move_tag: lateCopyTag,
  };
  const count = await db('photo_trash').where({ id: claim.id, state: 'trashed' }).update(retaken);
  if (count !== 1) throw trashError('TRASH_BUSY', `Trash row ${claim.id} was taken over by another process`);
  Object.assign(claim, retaken);
}

/**
 * For a restore that lost its claim because the row is gone altogether: its
 * gallery was deleted meanwhile, or the sweep had put the entry back and it
 * was purged. Nobody will settle the copy this restore put at the photo's
 * place on S3: no photo row names it, the gallery delete did not see it, and
 * nothing would ever remove it. It is known by its ETag and goes. On local
 * storage a deleted gallery's folder goes as a whole.
 */
async function dropAbandonedRestoreCopy(claim, lateCopyTag) {
  const storage = getStorage();
  const tag = claim.move_tag || lateCopyTag;
  if (storage.kind() !== 's3' || !claim.trash_key || !tag) return;
  if (await db('photo_trash').where({ id: claim.id }).first('id')) return;
  const targetKey = claim.original_key;
  const atTarget = await storage.stat(targetKey);
  if (!atTarget || atTarget.etag !== tag) return;
  const relative = targetKey.replace(/^events\/active\//, '');
  if (await db('photos').where({ event_id: claim.event_id }).whereIn('path', [relative, targetKey]).first('id')) return;
  await storage.delete(targetKey);
}

/**
 * A folder request the photo waited on may have been decided while it was in
 * the trash; the decision only reached the photos that were in the gallery.
 * After the commit, like an upload that outlived the decision
 * (uploadPlacement.afterUploadPlacement): a decision made since sees the row
 * itself. The restore stands either way. Guarded on the photo still waiting
 * on that request, so a decision that got there first is not undone.
 */
async function settleFolderRequest(event, photoId) {
  try {
    const restored = await db('photos').where({ id: photoId }).first('pending_folder_request_id');
    if (!restored || !restored.pending_folder_request_id) return;
    const requestId = restored.pending_folder_request_id;
    const request = await db('folder_requests').where({ id: requestId, event_id: event.id })
      .first('status', 'approved_folder_id', 'fallback_folder_id');
    if (request && request.status === 'pending') return;
    const waiting = () => db('photos').where({ id: photoId, pending_folder_request_id: requestId });
    // Approved: the photo follows into the approved folder if that still
    // stands and the photo is where it waited: in the request's fallback
    // folder, or in none (the restore takes a photo out of a folder that was
    // deleted, and the request's fallback has moved on since). What
    // folderRequestService.approveRequest does to the photos in the gallery.
    if (request && request.status === 'approved' && request.approved_folder_id
      && await db('photo_categories').where({ id: request.approved_folder_id, event_id: event.id }).first('id')) {
      await waiting()
        .where((q) => {
          q.whereNull('folder_id');
          if (request.fallback_folder_id != null) q.orWhere('folder_id', request.fallback_folder_id);
        })
        .update({ folder_id: Number(request.approved_folder_id), pending_folder_request_id: null });
    }
    // Decided either way, or gone: the photo stops waiting.
    await waiting().update({ pending_folder_request_id: null });
  } catch (error) {
    logger.warn(`Could not settle the folder request of restored photo ${photoId}`, { error: error.message });
  }
}

/**
 * Put one trashed photo back, with its child rows, queued for processing so
 * its derived files are made again. Returns the id it now has (the original
 * one unless that is taken, see insertRestored). Throws (statusCode 409, with
 * a code) when it cannot, leaving the photo in the trash.
 */
async function restorePhoto(event, row) {
  if (event.is_archived === true || event.is_archived === 1) {
    throw trashError('EVENT_ARCHIVED', 'An archived gallery cannot take photos back');
  }
  const storage = getStorage();
  // Only for where the file goes, which no later change to the snapshot
  // alters. What is inserted is read again, inside the transaction.
  const photoRow = JSON.parse(row.photo_row);
  photoRow.path = restoredPath(event, photoRow, JSON.parse(row.children || '{}'));
  const targetKey = row.trash_key ? resolvePhotoStorageKey(event, photoRow) : null;

  // The claim names where the file is going: until the row is gone, the
  // folder watcher and the S3 importer leave a file at that key alone
  // (claimsIncomingFile) instead of importing it as a new photo.
  const stamp = nowIso();
  const claimed = await db('photo_trash').where({ id: row.id, state: 'trashed' })
    .update({ state: 'restoring', state_changed_at: stamp, original_key: targetKey, restore_move_at: null, move_tag: null });
  if (claimed !== 1) throw trashError('TRASH_BUSY', 'This photo is no longer in the trash');
  const claim = { ...row, state: 'restoring', state_changed_at: stamp, original_key: targetKey, move_tag: null };

  let moved = false;
  try {
    // Read outside the transaction: a schema lookup inside one deadlocks SQLite.
    const columns = new Set(Object.keys(await db('photos').columnInfo()));

    if (targetKey) {
      // Two entries can name one place (a photo deleted, another uploaded
      // under its name and deleted too). Each sees the other's claim, so at
      // most one goes on and neither file is overwritten.
      if (await db('photo_trash').where({ original_key: targetKey, state: 'restoring' }).whereNot({ id: row.id }).first('id')) {
        throw trashError('TRASH_BUSY', `Another photo is being restored to the place of "${row.filename}"`);
      }
      if (!(await storage.stat(row.trash_key))) throw trashError('TRASH_FILE_MISSING', `The file of "${row.filename}" is no longer in the trash`);
      if (await storage.stat(targetKey)) throw trashError('RESTORE_TARGET_EXISTS', `The gallery already holds a file named like "${row.filename}"`);
      // On the row before the first byte moves: from here on a file at the
      // destination is this restore's to take back (settleRestore).
      await holdClaim(claim, { restore_move_at: nowIso() });
      moved = true;
      await moveClaimed(claim, row.trash_key, targetKey, { intoPlace: true });
    } else {
      try {
        await fs.access(resolvePhotoFilePath(event, photoRow));
      } catch {
        throw trashError('TRASH_FILE_MISSING', `The file of "${row.filename}" is no longer in its external folder`);
      }
    }

    const forEngine = await snapshotCoercion();
    const photoId = await db.transaction((trx) => insertRestored(trx, event, claim, columns, forEngine));
    await settleFolderRequest(event, photoId);
    return photoId;
  } catch (error) {
    try {
      await retakeRestore(claim, moved, error.lateCopyTag);
      await settleRestore(claim, moved);
    } catch (undoError) {
      // Left `restoring`; the sweep moves the file back.
      logger.error(`Could not undo the restore of trash row ${row.id}`, { error: undoError.message });
      if (moved) {
        await dropAbandonedRestoreCopy(claim, error.lateCopyTag).catch((dropError) => {
          logger.error(`Could not remove the copy of trash row ${row.id}`, { error: dropError.message });
        });
      }
    }
    if (!error.statusCode && isUniqueViolation(error)) {
      throw trashError('RESTORE_CONFLICT', `"${row.filename}" is in the gallery again`);
    }
    throw error;
  }
}

/** Steps 2 and 3 of a purge, for a row this caller has claimed as `purging`. */
async function finishPurge(row) {
  if (row.trash_key) await getStorage().delete(row.trash_key);
  await db('photo_trash').where({ id: row.id, state: 'purging' }).del();
}

/** Delete one trashed photo for good. False when another caller got to the row first. */
async function purgeTrashRow(row) {
  const claimed = await db('photo_trash').where({ id: row.id, state: 'trashed' })
    .update({ state: 'purging', state_changed_at: nowIso() });
  if (claimed !== 1) return false;
  await finishPurge(row);
  return true;
}

/** A row a crash left mid-change: bring it to rest. */
async function reconcile(row) {
  // Take it over by replacing the token: a second replica's attempt then
  // matches nothing, and so does the next step of the request that left the
  // row, should it only have stalled.
  try {
    await holdClaim(row);
  } catch {
    return;
  }

  if (row.state === 'purging') return finishPurge(row);

  if (row.state === 'pending') return undoPending(row);

  // restoring: the transaction never committed, so no photo row exists.
  if (row.trash_key && !(await db('events').where({ id: row.event_id }).first('id'))) {
    await db('photo_trash').where({ id: row.id, state: 'restoring' }).update({ state: 'purging' });
    return finishPurge(row);
  }
  return settleRestore(row, Boolean(row.restore_move_at));
}

/**
 * The hourly sweep: finish what a crash interrupted, then delete for good
 * every trashed photo past its retention, and any whose gallery is gone.
 */
async function purgeExpired() {
  const staleBefore = new Date(Date.now() - STALE_MS).toISOString();
  const stale = await db('photo_trash')
    .whereIn('state', ['pending', 'restoring', 'purging'])
    .where('state_changed_at', '<', staleBefore)
    .limit(PURGE_BATCH);
  for (const row of stale) {
    try {
      await reconcile(row);
    } catch (error) {
      logger.error(`Photo trash: could not reconcile row ${row.id}`, { error: error.message });
    }
  }

  let purged = 0;
  const due = await db('photo_trash')
    .where({ state: 'trashed' })
    .where((q) => q.where('purge_after', '<=', nowIso()).orWhereNotIn('event_id', db('events').select('id')))
    .limit(PURGE_BATCH);
  for (const row of due) {
    try {
      if (await purgeTrashRow(row)) purged += 1;
    } catch (error) {
      logger.error(`Photo trash: could not purge row ${row.id}`, { error: error.message });
    }
  }
  if (purged) logger.info(`Photo trash: purged ${purged} photo(s) past their retention`);
  return { purged, reconciled: stale.length };
}

/**
 * For an event that is being deleted: the storage keys of its trash, read
 * in the transaction that deletes the rows (`conn`), right before it does,
 * and deleted by the caller after the commit like the event's other
 * objects. Read any earlier, a photo trashed in between would lose its row
 * and keep its file. A trashing that has not committed by then loses its
 * claim with the row and removes its own file (dropAbandonedTrashFile).
 */
async function eventTrashKeys(eventId, conn = db) {
  return conn('photo_trash').where({ event_id: eventId }).whereNotNull('trash_key').pluck('trash_key');
}

const task = scheduledTask(async () => {
  try {
    await purgeExpired();
  } catch (error) {
    logger.error('Photo trash sweep failed', { error: error.message });
  }
}, { schedule: '37 * * * *' });
function startPhotoTrashPurge() { task.start(); }
const stopPhotoTrashPurge = () => task.stop();

