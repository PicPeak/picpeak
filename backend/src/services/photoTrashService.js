'use strict';

/**
 * The photo trash (issue 1733, item D2).
 *
 * A photo an admin deletes is moved, not destroyed: its row goes into
 * `photo_trash` (migration 294) and its original under the `trash/` storage
 * prefix, for the retention the operator set. Derived files (thumbnail,
 * preview, hero, watermark, web copy) are dropped: restoring queues the photo
 * for processing again.
 *
 * An external photo's file is not PicPeak's to move. Its row is trashed, the
 * file stays on the mount, and an import exclusion keeps the folder watcher
 * from bringing it back meanwhile (what deleting one did before the trash).
 *
 * ORDER OF OPERATIONS. Neither the file move nor the database write can roll
 * the other back, so every multi-step change is fenced by `photo_trash.state`
 * and ordered so that at every instant the original is at one of the two keys
 * the trash row names, and a row (the photo or the trash row) owns it:
 *
 *   trash    1. insert the trash row as `pending`   (photo row still there)
 *            2. move the file to trash_key
 *            3. one transaction: snapshot and delete the child rows, delete
 *               the photo row, flip the trash row to `trashed`
 *            A crash before 3 leaves the photo in the gallery; the sweep
 *            moves the file back and drops the pending row (undoPending).
 *
 *   restore  1. claim the row: `trashed` -> `restoring`
 *            2. move the file back
 *            3. one transaction: insert the photo and child rows, delete the
 *               trash row
 *            A crash before 3 leaves the row `restoring`; the sweep moves the
 *            file to trash_key again and the row back to `trashed`.
 *
 *   purge    1. claim the row: `trashed` -> `purging`
 *            2. delete the file (already gone is fine)
 *            3. delete the row
 *            File before row, so a crash leaves a row that the sweep retries
 *            rather than a file nothing points at.
 *
 * The claims are single UPDATEs guarded on the previous state, so two
 * replicas (or a double click) cannot both act on one row.
 *
 * THE FOLDER WATCHER. On local storage fileWatcher drops the photo row of a
 * file it sees leave events/active, and imports a file it sees arrive; the
 * S3 importer does the latter for a bucket. Both ask here first:
 * ownsOutgoingFile tells the watcher that a removal is step 2 of a trashing
 * (so it touches nothing, and photo.deleted fires once, from the delete
 * route), claimsIncomingFile tells both that an arriving file belongs to a
 * restore whose transaction is about to insert its row. As a second line,
 * nothing here reads "the photo row is gone" as "the file may go": see
 * commitTrash and undoPending.
 */

const path = require('path');
const crypto = require('crypto');
const fs = require('fs').promises;
const { db } = require('../database/db');
const logger = require('../utils/logger');
const { getStorage } = require('./storage');
const { resolvePhotoStorageKey, resolvePhotoFilePath } = require('./photoResolver');
const { photoCapOf, insertPhotoWithinCap, photoCapError } = require('./photoCap');
const { scheduledTask } = require('./scheduledTask');

const SETTING_KEY = 'general_photo_trash_retention_days';
const DEFAULT_RETENTION_DAYS = 30;
const MAX_RETENTION_DAYS = 365;
const TRASH_PREFIX = 'trash';
// A pending/restoring/purging row older than this was left by a crash.
const STALE_MS = 15 * 60 * 1000;
const PURGE_BATCH = 200;
const S3_COPY_LIMIT_BYTES = 5 * 1024 * 1024 * 1024;

// Regenerated by processing after a restore, so never carried back.
const DERIVED_RESET = {
  thumbnail_path: null, hero_path: null, hero_anchor: null, preview_path: null, web_path: null,
  watermark_path: null, watermark_generated_at: null,
  processing_status: 'pending', processing_error: null, processing_started_at: null,
  processing_attempts: 0, processing_retry_at: null, processing_attempt_id: null,
  web_status: null, web_started_at: null, web_error: null, web_attempt_id: null, web_attempts: 0, web_retry_at: null,
  face_status: null, face_count: null, face_started_at: null, face_error: null,
};

/** An error the routes answer with 409 and its code. */
function trashError(code, message) {
  return Object.assign(new Error(message), { code, statusCode: 409 });
}

const nowIso = () => new Date().toISOString();

/** Days a deleted photo stays restorable; 0 deletes at once, as before the trash. */
async function getRetentionDays() {
  try {
    const row = await db('app_settings').where({ setting_key: SETTING_KEY }).first();
    let value = row ? row.setting_value : null;
    if (typeof value === 'string') {
      try { value = JSON.parse(value); } catch { /* keep the string */ }
    }
    const days = Number(value);
    if (value === null || value === '' || !Number.isInteger(days) || days < 0) return DEFAULT_RETENTION_DAYS;
    return Math.min(days, MAX_RETENTION_DAYS);
  } catch (error) {
    // Unknown is not "0": keep what was deleted.
    logger.error('Failed to read the photo trash retention setting:', error.message);
    return DEFAULT_RETENTION_DAYS;
  }
}

async function dropDerivedFiles(photo) {
  const storage = getStorage();
  for (const key of [photo.thumbnail_path, photo.hero_path, photo.preview_path, photo.web_path, photo.watermark_path]) {
    if (key) await storage.delete(key).catch(() => {});
  }
  const imageProcessor = require('./imageProcessor');
  await imageProcessor.deletePreviewTiers(photo).catch(() => {});
  await imageProcessor.deleteThumbnailTiers(photo).catch(() => {});
}

/**
 * The child rows of a photo, inside the trashing transaction: the ones a user
 * would miss are returned for the trash row, every one is deleted (SQLite does
 * not enforce the foreign keys, so nothing cascades there).
 */
async function detachChildren(trx, photo, event) {
  const photoId = photo.id;
  const children = {
    event_slug: event.slug,
    feedback: await trx('photo_feedback').where({ photo_id: photoId }),
    admin_marks: await trx('photo_admin_marks').where({ photo_id: photoId }),
    transfer_files: await trx('transfer_files').where({ photo_id: photoId }),
    event_hero: Number(event.hero_photo_id) === Number(photoId),
    category_hero_ids: await trx('photo_categories').where({ hero_photo_id: photoId }).pluck('id'),
  };

  // Faces and embeddings are biometric and regenerable: never kept. The
  // purge also rebuilds the people the faces belonged to.
  let purgePhotoFaces = null;
  try { ({ purgePhotoFaces } = require('./faceProcessor')); } catch { /* face detection not installed */ }
  if (purgePhotoFaces) await purgePhotoFaces(photoId, trx);
  else await trx('photo_faces').where({ photo_id: photoId }).del();

  await trx('photo_feedback').where({ photo_id: photoId }).del();
  await trx('photo_admin_marks').where({ photo_id: photoId }).del();
  await trx('transfer_files').where({ photo_id: photoId }).del();
  // Download grants and per-view logs end with the photo's time in the gallery.
  await trx('event_download_grants').where({ photo_id: photoId }).del();
  await trx('image_access_logs').where({ photo_id: photoId }).del();
  await trx('events').where({ hero_photo_id: photoId }).update({ hero_photo_id: null });
  await trx('photo_categories').where({ hero_photo_id: photoId }).update({ hero_photo_id: null });
  return children;
}

/**
 * Step 3 of a trashing: the photo row and its children go, the trash row
 * comes to rest, in one transaction.
 *
 * The photo row may already be gone: on local storage the folder watcher
 * drops the row of a file it sees leave events/active, and step 2 is such a
 * move. The file is in the trash by then, so that is not a reason to stop:
 * the row read before the move stands in for the live one.
 */
async function commitTrash(row, photo, event) {
  await db.transaction(async (trx) => {
    const live = (await trx('photos').where({ id: row.photo_id, event_id: row.event_id }).first()) || photo;
    const children = await detachChildren(trx, live, event);
    await trx('photos').where({ id: row.photo_id, event_id: row.event_id }).del();
    const flipped = await trx('photo_trash').where({ id: row.id, state: 'pending' }).update({
      state: 'trashed',
      state_changed_at: nowIso(),
      photo_row: JSON.stringify(live),
      children: JSON.stringify(children),
    });
    if (flipped !== 1) throw trashError('TRASH_BUSY', `Trash row for photo ${row.photo_id} changed underneath`);
  });
}

/**
 * A trashing that did not reach step 3: put things back, without ever
 * deleting the only copy of the file.
 *   - original still in place (an S3 move is copy then delete): the copy
 *     under trash_key is surplus, drop it and the pending row
 *   - file in the trash, photo row still there: move it back
 *   - file in the trash, photo row gone (the watcher, see commitTrash):
 *     there is no gallery row to give it back to, so finish the trashing
 * Returns true when the photo ended up in the trash after all.
 */
async function undoPending(row) {
  if (row.trash_key) {
    const storage = getStorage();
    if (await storage.stat(row.original_key)) {
      await storage.delete(row.trash_key);
    } else if (await storage.stat(row.trash_key)) {
      if (!(await db('photos').where({ id: row.photo_id, event_id: row.event_id }).first('id'))) {
        const event = await db('events').where({ id: row.event_id }).first();
        await commitTrash(row, JSON.parse(row.photo_row), event || { id: row.event_id });
        return true;
      }
      await storage.rename(row.trash_key, row.original_key);
    }
  }
  await db('photo_trash').where({ id: row.id, state: 'pending' }).del();
  return false;
}

/**
 * Move one photo to the trash. Returns false, having changed nothing, when a
 * managed photo's original is already missing: there is nothing to keep, and
 * the caller deletes the row the way it always did. Throws when the photo
 * could not be trashed; it is then still in the gallery, untouched.
 */
async function trashPhoto(event, photo, admin, retentionDays) {
  const storage = getStorage();
  let originalKey;
  try {
    originalKey = resolvePhotoStorageKey(event, photo);
  } catch {
    // A row without a path names no file.
    return false;
  }
  const stat = originalKey ? await storage.stat(originalKey) : null;
  if (originalKey && !stat) return false;
  // S3 moves an object with CopyObject, which stops at 5 GB, and the adapter
  // has no multipart copy. Refused before anything is touched.
  if (stat && storage.kind() === 's3' && Number(stat.size) > S3_COPY_LIMIT_BYTES) {
    throw trashError('TRASH_TOO_LARGE',
      `"${photo.original_filename || photo.filename}" is larger than 5 GB, which S3 cannot move to the trash. `
      + 'It was not deleted. Set the trash retention to 0 to delete it for good.');
  }

  const now = new Date();
  const base = {
    photo_id: photo.id,
    event_id: event.id,
    state: 'pending',
    state_changed_at: now.toISOString(),
    filename: photo.original_filename || photo.filename,
    size_bytes: Number(photo.size_bytes) || 0,
    original_key: originalKey,
    trash_key: originalKey
      ? path.posix.join(TRASH_PREFIX, String(event.id), crypto.randomUUID(), path.posix.basename(originalKey))
      : null,
    deleted_at: now.toISOString(),
    deleted_by: admin?.id ?? null,
    deleted_by_name: admin?.username ?? null,
    purge_after: new Date(now.getTime() + retentionDays * 86400000).toISOString(),
    photo_row: JSON.stringify(photo),
    children: '{}',
  };

  // A row a crashed attempt left for this photo: put it right, then go on.
  const leftover = await db('photo_trash').where({ photo_id: photo.id, state: 'pending' }).first();
  if (leftover) {
    if (Date.now() - Date.parse(leftover.state_changed_at) < STALE_MS) {
      throw trashError('TRASH_BUSY', `Photo ${photo.id} is already being moved to the trash`);
    }
    await undoPending(leftover);
  }

  const inserted = await db('photo_trash').insert(base).returning('id');
  const row = { ...base, id: inserted[0]?.id ?? inserted[0] };

  try {
    if (row.trash_key) await storage.rename(row.original_key, row.trash_key);
    // Before the transaction, like the delete it replaces: the watcher must
    // not re-import the file while the row is in the trash.
    await require('./externalImportService').recordExclusions(Number(event.id), [photo]);

    await commitTrash(row, photo, event);
  } catch (error) {
    let trashedAfterAll = false;
    try {
      trashedAfterAll = await undoPending(row);
    } catch (undoError) {
      // The sweep finishes the undo; the pending row still names both keys.
      logger.error(`Could not undo the trashing of photo ${photo.id}`, { error: undoError.message });
    }
    if (!trashedAfterAll) throw error;
  }

  await dropDerivedFiles(photo).catch((error) => {
    logger.warn(`Could not drop derived files of trashed photo ${photo.id}`, { error: error.message });
  });
  return true;
}

function publicRow(row) {
  let mediaType = 'image';
  try { mediaType = JSON.parse(row.photo_row).media_type || 'image'; } catch { /* keep the default */ }
  return {
    id: row.id,
    photo_id: row.photo_id,
    filename: row.filename,
    media_type: mediaType,
    size_bytes: Number(row.size_bytes) || 0,
    deleted_at: row.deleted_at,
    deleted_by_name: row.deleted_by_name,
    purge_after: row.purge_after,
  };
}

async function listTrash(eventId) {
  const rows = await db('photo_trash')
    .where({ event_id: eventId, state: 'trashed' })
    .orderBy('deleted_at', 'desc')
    .orderBy('id', 'desc');
  return rows.map(publicRow);
}

/**
 * A photo row without a guest who uploaded it: what photoCredit's
 * clearGuestCredits does to the live rows of a forgotten guest.
 */
function withoutGuest(photoRow, guestId) {
  if (Number(photoRow.uploader_guest_id) !== Number(guestId)) return photoRow;
  if (photoRow.credit_source === 'guest') {
    return { ...photoRow, credit_name: null, credit_source: null, uploader_guest_id: null, credit_visible_to_guests: false };
  }
  if (photoRow.credit_source === 'manual') return { ...photoRow, credit_name: null, uploader_guest_id: null };
  return { ...photoRow, uploader_guest_id: null };
}

/**
 * A guest was forgotten (the admin removed them, or they asked): the same
 * happens to what the trash holds of them as to their live rows. Their
 * feedback keeps its count and loses the identity
 * (feedbackService.anonymizeGuestFeedback), their name leaves the photos
 * they uploaded. Not left for the purge: a snapshot is restorable data.
 */
async function forgetGuest(guestId) {
  const id = Number(guestId);
  const guest = await db('gallery_guests').where({ id }).first('event_id');
  if (!guest) return 0;
  let changed = 0;
  for (const row of await db('photo_trash').where({ event_id: guest.event_id }).select('id', 'photo_row', 'children')) {
    const photoRow = JSON.parse(row.photo_row);
    const children = JSON.parse(row.children || '{}');
    const scrubbedRow = withoutGuest(photoRow, id);
    let touched = scrubbedRow !== photoRow;
    children.feedback = (children.feedback || []).map((feedback) => {
      if (Number(feedback.guest_id) !== id) return feedback;
      touched = true;
      return { ...feedback, guest_id: null, guest_name: null, guest_email: null };
    });
    if (!touched) continue;
    await db('photo_trash').where({ id: row.id })
      .update({ photo_row: JSON.stringify(scrubbedRow), children: JSON.stringify(children) });
    changed += 1;
  }
  return changed;
}

/**
 * For the folder watcher: is the file that just left `storageKey` this
 * photo's original on its way into the trash? Then the removal is the app's
 * own move, not someone deleting the file, and the photo row and its children
 * belong to the trashing transaction.
 */
async function ownsOutgoingFile(photoId, storageKey) {
  return Boolean(await db('photo_trash').where({ photo_id: photoId, original_key: storageKey }).first('id'));
}

/**
 * For the folder watcher and the S3 importer: is a restore putting a file at
 * `storageKey` right now? Its photo row follows in the restore's transaction,
 * so the file must not be imported as a new photo.
 */
async function claimsIncomingFile(storageKey) {
  return Boolean(await db('photo_trash').where({ original_key: storageKey, state: 'restoring' }).first('id'));
}

/** Where a trashed managed photo goes back to, with the event's current slug. */
function restoredPath(event, photoRow, children) {
  const oldSlug = children.event_slug;
  if (!oldSlug || oldSlug === event.slug || !photoRow.path) return photoRow.path;
  // The same rewrite an event rename applies to its photos.
  return photoRow.path.replace(oldSlug, event.slug);
}

/**
 * Step 3 of a restore. The photo gets its old id back when that is still
 * free. It is not always: restoring a database backup resets the id sequence
 * to the highest live photo, so a later upload can hold the id of a photo
 * still in the trash. The photo then comes back under a new id; its child
 * rows are written from the snapshot either way and follow it.
 * Returns the id the photo now has.
 */
async function insertRestored(trx, event, row, photoRow, children, columns) {
  const record = {};
  for (const [key, value] of Object.entries({ ...photoRow, ...DERIVED_RESET })) {
    if (columns.has(key)) record[key] = value;
  }
  delete record.id;
  record.event_id = event.id;
  // Processing reads this: a restored photo was announced when it was
  // uploaded and is not announced again (photoProcessor.processPhoto).
  if (columns.has('restored_from_trash_at')) record.restored_from_trash_at = nowIso();
  const keepsId = !(await trx('photos').where({ id: row.photo_id }).first('id'));
  if (keepsId) record.id = row.photo_id;

  // What the row pointed at may have been deleted while it was in the trash.
  const exists = async (table, id, extra = {}) => Boolean(id && await trx(table).where({ id, ...extra }).first('id'));
  if (!(await exists('photo_categories', record.category_id, { event_id: event.id }))) record.category_id = null;
  if (!(await exists('photo_categories', record.folder_id, { event_id: event.id }))) record.folder_id = null;
  if (!(await exists('admin_users', record.uploaded_by_admin_id))) record.uploaded_by_admin_id = null;
  if (record.uploader_guest_id && !(await exists('gallery_guests', record.uploader_guest_id))) {
    Object.assign(record, withoutGuest(record, record.uploader_guest_id));
  }

  const inserted = await insertPhotoWithinCap(record, photoCapOf(event), trx);
  if (!inserted) throw trashError('PHOTO_CAP_REACHED', photoCapError(photoCapOf(event)).error);
  const photoId = keepsId ? row.photo_id : (inserted[0]?.id ?? inserted[0]);
  if (keepsId && trx.client.config.client === 'pg') {
    // An explicit id does not move a PostgreSQL sequence, and after a backup
    // restore the id can lie ahead of it: a later upload would collide.
    await trx.raw(
      'SELECT setval(seq, GREATEST(nextval(seq), (SELECT MAX(id) FROM photos))) FROM (SELECT pg_get_serial_sequence(?, ?) AS seq) s',
      ['photos', 'id']
    );
  }

  for (const feedback of children.feedback || []) {
    const { id: _id, ...rest } = feedback;
    // A guest that no longer exists keeps the count, not the name: what
    // forgetting a guest does to feedback in the gallery.
    const kept = rest.guest_id && !(await exists('gallery_guests', rest.guest_id))
      ? { ...rest, guest_id: null, guest_name: null, guest_email: null }
      : rest;
    await trx('photo_feedback').insert({ ...kept, photo_id: photoId, event_id: event.id });
  }
  for (const mark of children.admin_marks || []) {
    const { id: _id, ...rest } = mark;
    if (await exists('admin_users', rest.admin_id)) {
      await trx('photo_admin_marks').insert({ ...rest, photo_id: photoId, event_id: event.id });
    }
  }
  for (const file of children.transfer_files || []) {
    const { id: _id, ...rest } = file;
    if (await exists('transfers', rest.transfer_id)) await trx('transfer_files').insert({ ...rest, photo_id: photoId });
  }
  if (children.event_hero) {
    await trx('events').where({ id: event.id }).whereNull('hero_photo_id').update({ hero_photo_id: photoId });
  }
  if ((children.category_hero_ids || []).length) {
    await trx('photo_categories').where({ event_id: event.id }).whereIn('id', children.category_hero_ids)
      .whereNull('hero_photo_id').update({ hero_photo_id: photoId });
  }
  if (record.external_relpath) {
    await trx('external_import_exclusions')
      .where({ event_id: event.id, external_relpath: record.external_relpath }).del();
  }

  const removed = await trx('photo_trash').where({ id: row.id, state: 'restoring' }).del();
  if (removed !== 1) throw trashError('TRASH_BUSY', `Trash row ${row.id} changed underneath`);
  return photoId;
}

/**
 * Put one trashed photo back, with its child rows, queued for processing so
 * its derived files are made again. Returns the id it now has (the original
 * one unless that is taken, see insertRestored). Throws (statusCode 409, with
 * a code) when it cannot, leaving the photo in the trash.
 */
async function restorePhoto(event, row) {
  if (event.is_archived === true || event.is_archived === 1) {
    throw trashError('EVENT_ARCHIVED', 'An archived gallery cannot take photos back');
  }
  const storage = getStorage();
  const photoRow = JSON.parse(row.photo_row);
  const children = JSON.parse(row.children || '{}');
  photoRow.path = restoredPath(event, photoRow, children);
  const targetKey = row.trash_key ? resolvePhotoStorageKey(event, photoRow) : null;

  // The claim names where the file is going: until the row is gone, the
  // folder watcher and the S3 importer leave a file at that key alone
  // (claimsIncomingFile) instead of importing it as a new photo.
  const claimed = await db('photo_trash').where({ id: row.id, state: 'trashed' })
    .update({ state: 'restoring', state_changed_at: nowIso(), original_key: targetKey });
  if (claimed !== 1) throw trashError('TRASH_BUSY', 'This photo is no longer in the trash');

  let moved = false;
  try {
    // Read outside the transaction: a schema lookup inside one deadlocks SQLite.
    const columns = new Set(Object.keys(await db('photos').columnInfo()));

    if (targetKey) {
      if (!(await storage.stat(row.trash_key))) throw trashError('TRASH_FILE_MISSING', `The file of "${row.filename}" is no longer in the trash`);
      if (await storage.stat(targetKey)) throw trashError('RESTORE_TARGET_EXISTS', `The gallery already holds a file named like "${row.filename}"`);
      await storage.rename(row.trash_key, targetKey);
      moved = true;
    } else {
      try {
        await fs.access(resolvePhotoFilePath(event, photoRow));
      } catch {
        throw trashError('TRASH_FILE_MISSING', `The file of "${row.filename}" is no longer in its external folder`);
      }
    }

    return await db.transaction((trx) => insertRestored(trx, event, row, photoRow, children, columns));
  } catch (error) {
    try {
      if (moved) await storage.rename(targetKey, row.trash_key);
      await db('photo_trash').where({ id: row.id, state: 'restoring' })
        .update({ state: 'trashed', state_changed_at: nowIso() });
    } catch (undoError) {
      // Left `restoring`; the sweep moves the file back.
      logger.error(`Could not undo the restore of trash row ${row.id}`, { error: undoError.message });
    }
    if (!error.statusCode && require('../utils/dbErrors').isUniqueViolation(error)) {
      throw trashError('RESTORE_CONFLICT', `"${row.filename}" is in the gallery again`);
    }
    throw error;
  }
}

/** Steps 2 and 3 of a purge, for a row this caller has claimed as `purging`. */
async function finishPurge(row) {
  if (row.trash_key) await getStorage().delete(row.trash_key);
  await db('photo_trash').where({ id: row.id, state: 'purging' }).del();
}

/** Delete one trashed photo for good. False when another caller got to the row first. */
async function purgeTrashRow(row) {
  const claimed = await db('photo_trash').where({ id: row.id, state: 'trashed' })
    .update({ state: 'purging', state_changed_at: nowIso() });
  if (claimed !== 1) return false;
  await finishPurge(row);
  return true;
}

/** A row a crash left mid-change: bring it to rest. */
async function reconcile(row) {
  // Take it over by moving the timestamp; a second replica's UPDATE then matches nothing.
  const mine = await db('photo_trash')
    .where({ id: row.id, state: row.state, state_changed_at: row.state_changed_at })
    .update({ state_changed_at: nowIso() });
  if (mine !== 1) return;

  if (row.state === 'purging') return finishPurge(row);

  if (row.state === 'pending') return undoPending(row);

  // restoring: the transaction never committed, so no photo row exists.
  if (row.trash_key) {
    const storage = getStorage();
    const event = await db('events').where({ id: row.event_id }).first();
    if (!event) {
      await db('photo_trash').where({ id: row.id, state: 'restoring' }).update({ state: 'purging' });
      return finishPurge(row);
    }
    // Where the file was going: the claim recorded it.
    const targetKey = row.original_key;
    if (await storage.stat(row.trash_key)) {
      // The restore checked the target was free before copying, and nothing
      // imports a file there while the row is `restoring`: a file no photo
      // row names is the copy.
      const relative = targetKey.replace(/^events\/active\//, '');
      if (!(await db('photos').where({ event_id: row.event_id }).whereIn('path', [relative, targetKey]).first('id'))) {
        await storage.delete(targetKey);
      }
    } else if (await storage.stat(targetKey)) {
      await storage.rename(targetKey, row.trash_key);
    }
  }
  await db('photo_trash').where({ id: row.id, state: 'restoring' })
    .update({ state: 'trashed', state_changed_at: nowIso() });
}

/**
 * The hourly sweep: finish what a crash interrupted, then delete for good
 * every trashed photo past its retention, and any whose gallery is gone.
 */
async function purgeExpired() {
  const staleBefore = new Date(Date.now() - STALE_MS).toISOString();
  const stale = await db('photo_trash')
    .whereIn('state', ['pending', 'restoring', 'purging'])
    .where('state_changed_at', '<', staleBefore)
    .limit(PURGE_BATCH);
  for (const row of stale) {
    try {
      await reconcile(row);
    } catch (error) {
      logger.error(`Photo trash: could not reconcile row ${row.id}`, { error: error.message });
    }
  }

  let purged = 0;
  const due = await db('photo_trash')
    .where({ state: 'trashed' })
    .where((q) => q.where('purge_after', '<=', nowIso()).orWhereNotIn('event_id', db('events').select('id')))
    .limit(PURGE_BATCH);
  for (const row of due) {
    try {
      if (await purgeTrashRow(row)) purged += 1;
    } catch (error) {
      logger.error(`Photo trash: could not purge row ${row.id}`, { error: error.message });
    }
  }
  if (purged) logger.info(`Photo trash: purged ${purged} photo(s) past their retention`);
  return { purged, reconciled: stale.length };
}

/**
 * For an event that is being deleted: the storage keys of its trash, read
 * before the transaction that deletes the rows, deleted by the caller after
 * the commit like the event's other objects.
 */
async function eventTrashKeys(eventId) {
  return db('photo_trash').where({ event_id: eventId }).whereNotNull('trash_key').pluck('trash_key');
}

const task = scheduledTask(async () => {
  try {
    await purgeExpired();
  } catch (error) {
    logger.error('Photo trash sweep failed', { error: error.message });
  }
}, { schedule: '37 * * * *' });
function startPhotoTrashPurge() { task.start(); }
const stopPhotoTrashPurge = () => task.stop();

